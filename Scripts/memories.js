// =========================
// Current Memory
// =========================

let currentMemory = null;

let currentPhotoIndex = 0;


// =========================
// Open Memory
// =========================

function openMemory(number) {

    currentMemory = memories[number];

    currentPhotoIndex = 0;


    document.getElementById("memoryTitle").textContent =
        currentMemory.title;


    document.getElementById("memoryModal").style.display =
        "flex";


    showPhoto();
}


// =========================
// Show Photo
// =========================

function showPhoto() {

    if (!currentMemory) return;


    const photo =
        currentMemory.photos[currentPhotoIndex];


    const image =
        document.getElementById("currentPhoto");


    // وضع الصورة
    image.src = photo.image;


    // الكلام اللي هيظهر على ضهر الصورة
    const backText =
        document.getElementById("photoBackText");


    if (backText) {

        backText.textContent =
            photo.text;
    }


    // رقم الصورة

    const counter =
        document.getElementById("photoCounter");


    if (counter) {

        counter.textContent =
            `${currentPhotoIndex + 1} / ${currentMemory.photos.length}`;
    }


    // =========================
    // رجّع الصورة للوش
    // =========================

    const flipInner =
        document.querySelector(".flip-inner");


    if (flipInner) {

        flipInner.classList.remove("flipped");
    }


    // =========================
    // Previous Button
    // =========================

    const prevButton =
        document.querySelector(".prev-btn");


    if (prevButton) {

        prevButton.disabled =
            currentPhotoIndex === 0;
    }


    // =========================
    // Next Button
    // =========================

    const nextButton =
        document.querySelector(".next-btn");


    if (nextButton) {

        nextButton.disabled =
            currentPhotoIndex ===
            currentMemory.photos.length - 1;
    }

}


// =========================
// Flip Photo
// Double Click
// =========================

function flipPhoto() {

    const flipInner =
        document.querySelector(".flip-inner");


    if (flipInner) {

        flipInner.classList.toggle("flipped");
    }

}


// =========================
// Next Photo
// =========================

function nextPhoto() {

    if (!currentMemory) return;


    if (
        currentPhotoIndex <
        currentMemory.photos.length - 1
    ) {

        currentPhotoIndex++;

        showPhoto();
    }

}


// =========================
// Previous Photo
// =========================

function previousPhoto() {

    if (!currentMemory) return;


    if (currentPhotoIndex > 0) {

        currentPhotoIndex--;

        showPhoto();
    }

}


// =========================
// Close Memory
// =========================

function closeMemory() {

    document.getElementById("memoryModal").style.display =
        "none";


    // لما تقفلي النافذة
    // رجّعي الكارت للوش

    const flipInner =
        document.querySelector(".flip-inner");


    if (flipInner) {

        flipInner.classList.remove("flipped");
    }

}